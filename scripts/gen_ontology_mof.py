# ---------- 表記ゆれの自動追加 ----------
def fw(s: str, dash: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "-":
            out.append(dash)
        elif 0x21 <= o <= 0x7E:
            out.append(chr(o + 0xFEE0))
        else:
            out.append(ch)
    return "".join(out)

def variants(s: str) -> list[str]:
    if not re.search(r"[A-Za-z0-9]", s):
        return [s]
    vs = [s]
    if "-" in s:
        vs += [s.replace("-", "−"), s.replace("-", "‐")]
    vs += [fw(s, "−"), fw(s, "－")]
    if " " in s:
        vs.append(s.replace(" ", ""))
    seen, out = set(), []
    for v in vs:
        if v not in seen:
            seen.add(v); out.append(v)
    return out

def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

